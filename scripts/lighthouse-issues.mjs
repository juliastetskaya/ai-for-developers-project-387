import { execFileSync } from 'node:child_process';
import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  LIGHTHOUSE_LABEL,
  LIGHTHOUSE_TEST_LABEL,
  MAX_NEW_ISSUES,
  applyTestTitle,
  assertTestModeAllowed,
  buildMarker,
  buildTestMarker,
  escapeHtmlComments,
  extractFindings,
  findingFingerprint,
  findSoftDuplicate,
  parseBooleanEnv,
  parseIssueMarkers,
  realIssueLabels,
  reviewFinding,
  testIssueLabels,
} from './lighthouse-findings.mjs';
import { TEST_FINDING_FINGERPRINT, testFinding } from './lighthouse-test-fixture.mjs';

const ARTIFACT_NOTE = 'lighthouse-audit';

function defaultRunGh(args) {
  try {
    return execFileSync('gh', args, { encoding: 'utf8' });
  } catch (error) {
    const stderr = error.stderr ? String(error.stderr).trim() : error.message;
    throw new Error(`gh ${args.slice(0, 3).join(' ')} failed: ${stderr}`);
  }
}

function truncate(value, limit) {
  const text = String(value ?? '');
  return text.length > limit ? `${text.slice(0, limit)}…` : text;
}

export function collectIssues({ runGh, repo, label }) {
  const output = runGh([
    'issue',
    'list',
    '--repo',
    repo,
    '--label',
    label,
    '--state',
    'all',
    '--limit',
    '500',
    '--json',
    'number,state,title,url,body',
  ]);
  return JSON.parse(output || '[]');
}

function markerFingerprints(issue, kind) {
  const markers = parseIssueMarkers(issue.body);
  return (kind === 'test' ? markers.test : markers.real).map(
    (marker) => marker.fingerprint,
  );
}

export function fingerprintMatch(issues, fingerprint, kind) {
  for (const issue of issues) {
    if (markerFingerprints(issue, kind).includes(fingerprint)) return issue;
  }
  return null;
}

function evidenceLine(finding) {
  const evidence = finding.evidence ?? {};
  if (evidence.resource) return `Resource: \`${escapeHtmlComments(evidence.resource)}\``;
  if (evidence.selector) return `Selector: \`${escapeHtmlComments(evidence.selector)}\``;
  return `Snippet: \`${escapeHtmlComments(truncate(evidence.snippet, 200))}\``;
}

export function buildRealIssue(finding, { runUrl, appUrl }) {
  const title = finding.title.replace(/\s+/g, ' ').trim();
  const body = [
    buildMarker(finding),
    `> Automated finding from the scheduled Lighthouse audit of ${escapeHtmlComments(appUrl)}${escapeHtmlComments(finding.route)}.`,
    '',
    `- Lighthouse audit: \`${escapeHtmlComments(finding.audit)}\` (${escapeHtmlComments(finding.category)})`,
    `- Severity: ${escapeHtmlComments(finding.severity)}`,
    `- Fingerprint: \`${escapeHtmlComments(finding.fingerprint)}\` (stable: the issue is not duplicated while it stays open)`,
    `- Workflow run: ${escapeHtmlComments(runUrl)}`,
    `- Lighthouse artifact: \`${ARTIFACT_NOTE}\` (JSON and HTML reports)`,
    '',
    '## Evidence',
    '',
    `- ${evidenceLine(finding)}`,
  ];
  if (finding.evidence?.observation) {
    body.push(`- Observed: ${escapeHtmlComments(finding.evidence.observation)}`);
  }
  body.push(
    '',
    '## Suggested fix',
    '',
    escapeHtmlComments(finding.fix),
    '',
    '## Impact',
    '',
    escapeHtmlComments(finding.impact),
    '',
    '## Repository evidence',
    '',
    `\`${escapeHtmlComments(finding.repo_evidence.file)}\` — \`${escapeHtmlComments(finding.repo_evidence.symbol)}\``,
    '',
    '<sub>Generated by the Lighthouse audit workflow. The analysis is advisory: verify the finding against the current code before implementing it.</sub>',
    '',
  );
  return {
    title,
    labels: realIssueLabels(finding),
    body: body.join('\n'),
  };
}

export function buildTestIssue(finding, { runUrl, appUrl, createIssues }) {
  const body = [
    buildTestMarker(finding),
    '> **Synthetic test finding created by `test_mode`.**',
    '>',
    '> This issue demonstrates issue creation and deduplication of the Lighthouse audit',
    '> workflow. It is **not** a Lighthouse result and does **not** describe a verified',
    '> problem in the application. The real Lighthouse reports were not modified.',
    '',
    `- Lighthouse audit: \`${escapeHtmlComments(finding.audit)}\` (${escapeHtmlComments(finding.category)}) — synthetic`,
    `- Targeted page: ${escapeHtmlComments(appUrl)}${escapeHtmlComments(finding.route)}`,
    `- Fingerprint: \`${escapeHtmlComments(finding.fingerprint)}\` (stable: repeated test runs do not create another issue)`,
    `- Workflow run: ${escapeHtmlComments(runUrl)}`,
    `- Trigger: \`workflow_dispatch\` with \`test_mode=true\`, \`create_issues=${escapeHtmlComments(createIssues)}\``,
    `- Artifact: \`${ARTIFACT_NOTE}\` (real, unmodified Lighthouse JSON and HTML)`,
    `- Fixture: \`scripts/lighthouse-test-fixture.mjs\``,
    '',
    '## Synthetic finding',
    '',
    `- ${evidenceLine(finding)}`,
    `- Observed: ${escapeHtmlComments(finding.evidence.observation)}`,
    '',
    '## Suggested fix (illustrative)',
    '',
    escapeHtmlComments(finding.fix),
    '',
    '## Impact (illustrative)',
    '',
    escapeHtmlComments(finding.impact),
    '',
    '## Repository evidence',
    '',
    `\`${escapeHtmlComments(finding.repo_evidence.file)}\` — \`${escapeHtmlComments(finding.repo_evidence.symbol)}\``,
    '',
    '## Removing this issue',
    '',
    'Close it after the demonstration. It is never reopened or deleted automatically,',
    'and while it exists (open or closed) the workflow does not create another test',
    'issue. No comments are added to it, so a maintainer who wants a fresh',
    'demonstration can delete the issue and re-run the workflow manually.',
    '',
  ].join('\n');
  return {
    title: applyTestTitle(finding.title),
    labels: testIssueLabels(),
    body,
  };
}

function pushItem(items, item) {
  items.push({ ...item });
}

/**
 * Builds the full plan: every candidate is validated, classified and matched
 * against existing issues. No writes happen here.
 */
export function planIssues({
  report,
  testMode,
  createIssues,
  existingReal = [],
  existingTest = [],
  links,
  scope = null,
  deps = {},
}) {
  const { findings, error } = extractFindings(report);
  const items = [];
  const parsed = findings;

  const realFindings = parsed.filter((finding) => finding?.synthetic !== true);
  for (const finding of realFindings) {
    const fingerprint = findingFingerprint(finding);
    const candidate = { ...finding, fingerprint };
    const review = reviewFinding(candidate, { mode: 'real', scope, ...deps });
    if (!review.ok) {
      pushItem(items, {
        kind: 'real',
        fingerprint,
        audit: candidate.audit ?? null,
        route: candidate.route ?? null,
        decision: 'not_actionable',
        reason: review.reason,
        title: truncate(candidate.title ?? '(untitled)', 120),
      });
      continue;
    }
    if (testMode) {
      pushItem(items, {
        kind: 'real',
        fingerprint,
        audit: candidate.audit,
        route: candidate.route,
        decision: 'suppressed',
        reason: 'test_mode analyses real findings but publishes only the synthetic one',
        title: candidate.title,
      });
      continue;
    }
    const payload = buildRealIssue(candidate, links);
    const duplicate = fingerprintMatch(existingReal, fingerprint, 'real');
    if (duplicate) {
      pushItem(items, {
        kind: 'real',
        fingerprint,
        audit: candidate.audit,
        route: candidate.route,
        decision: 'duplicate',
        duplicate,
        title: payload.title,
        labels: payload.labels,
        body: payload.body,
      });
      continue;
    }
    const soft = findSoftDuplicate(candidate.title, existingReal);
    if (soft) {
      pushItem(items, {
        kind: 'real',
        fingerprint,
        audit: candidate.audit,
        route: candidate.route,
        decision: 'possible_duplicate',
        duplicate: soft.issue,
        reason: `title similarity ${soft.score.toFixed(2)}`,
        title: payload.title,
        labels: payload.labels,
        body: payload.body,
      });
      continue;
    }
    pushItem(items, {
      kind: 'real',
      fingerprint,
      audit: candidate.audit,
      route: candidate.route,
      decision: 'create',
      title: payload.title,
      labels: payload.labels,
      body: payload.body,
    });
  }

  if (testMode) {
    const canonical = testFinding();
    const agentTestFindings = parsed.filter((finding) => finding?.synthetic === true);
    const agentIncluded = agentTestFindings.some(
      (finding) => findingFingerprint(finding) === TEST_FINDING_FINGERPRINT,
    );
    // The canonical fixture is not trusted just because it ships with the
    // repository: it goes through the same test-mode review as any finding, so
    // a broken fixture cannot bypass the actionability gate.
    const review = reviewFinding(canonical, { mode: 'test', scope, ...deps });
    if (!review.ok) {
      pushItem(items, {
        kind: 'test',
        fingerprint: canonical.fingerprint ?? TEST_FINDING_FINGERPRINT,
        audit: canonical.audit,
        route: canonical.route,
        decision: 'not_actionable',
        reason: `the synthetic fixture failed validation: ${review.reason}`,
        agent_included: agentIncluded,
        title: applyTestTitle(canonical.title),
      });
    } else {
      const payload = buildTestIssue(canonical, { ...links, createIssues });
      const duplicate = fingerprintMatch(existingTest, TEST_FINDING_FINGERPRINT, 'test');
      pushItem(items, {
        kind: 'test',
        fingerprint: TEST_FINDING_FINGERPRINT,
        audit: canonical.audit,
        route: canonical.route,
        decision: duplicate ? 'duplicate' : 'create',
        duplicate: duplicate ?? null,
        agent_included: agentIncluded,
        title: payload.title,
        labels: payload.labels,
        body: payload.body,
      });
    }
  }

  let newIssues = 0;
  for (const item of items) {
    if (item.decision !== 'create') continue;
    if (item.kind === 'real') {
      newIssues += 1;
      if (newIssues > MAX_NEW_ISSUES) {
        item.decision = 'limit';
        item.reason = `at most ${MAX_NEW_ISSUES} real findings per run`;
      }
    }
  }

  return {
    items,
    error,
    createIssues,
    counts: {
      parsed: parsed.length,
      real: items.filter((item) => item.kind === 'real').length,
      test: items.filter((item) => item.kind === 'test').length,
      actionable: items.filter(
        (item) => item.kind === 'real' && item.decision === 'create',
      ).length,
    },
  };
}

/** Re-checks deduplication immediately before each create call. */
export function executePlan({ plan, runGh, repo, links, testMode }) {
  const results = [];
  for (const item of plan.items) {
    if (item.decision !== 'create') {
      results.push({ ...item });
      continue;
    }
    const label = item.kind === 'test' ? LIGHTHOUSE_TEST_LABEL : LIGHTHOUSE_LABEL;
    const fresh = collectIssues({ runGh, repo, label });
    const duplicate = fingerprintMatch(fresh, item.fingerprint, item.kind);
    if (duplicate) {
      results.push({
        ...item,
        decision: 'duplicate_before_create',
        duplicate,
        reason: `issue #${duplicate.number} appeared before creation`,
      });
      continue;
    }
    const args = ['issue', 'create', '--repo', repo, '--title', item.title, '--body', item.body];
    for (const labelName of item.labels) args.push('--label', labelName);
    const url = runGh(args).trim().split('\n').pop();
    results.push({ ...item, decision: 'created', issueUrl: url });
  }
  return { ...plan, items: results, mode: testMode ? 'test' : 'real', links };
}

export function renderIssues(plan) {
  const lines = ['# Lighthouse issues', ''];
  const created = plan.items.filter((item) => item.decision === 'created');
  const late = plan.items.filter((item) => item.decision === 'duplicate_before_create');
  if (created.length === 0 && late.length === 0) {
    lines.push('No issue was created in this run.');
  }
  for (const item of created) {
    lines.push(`- ${item.kind === 'test' ? 'test' : 'real'}: #${issueNumber(item.issueUrl)} — ${item.issueUrl}`);
    lines.push(`  - ${item.title}`);
  }
  for (const item of late) {
    lines.push(
      `- skipped ${item.kind} finding: issue #${item.duplicate.number} appeared before creation`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

function issueNumber(url) {
  const match = /\/(\d+)$/.exec(String(url ?? ''));
  return match ? match[1] : '?';
}

export function renderDecisions(plan, { eventName, testMode, appUrl }) {
  const lines = ['# Lighthouse issue decisions', ''];
  lines.push(`- Event: \`${eventName}\``);
  lines.push(`- App URL: ${appUrl}`);
  lines.push(`- Findings parsed from the AI report: ${plan.counts.parsed}`);
  lines.push(`- Real findings: ${plan.counts.real}`);
  lines.push(`- Synthetic test findings: ${plan.counts.test}`);
  lines.push('');
  if (plan.error) {
    lines.push(`## Report problem`, '', plan.error, '');
  }
  lines.push('## Test mode', '');
  lines.push(`- test_mode: ${testMode}`);
  lines.push(`- create_issues: ${plan.createIssues}`);
  if (!testMode) {
    lines.push('- outcome: not applicable (synthetic findings are disabled outside manual test runs)');
  } else {
    const testItem = plan.items.find((item) => item.kind === 'test');
    lines.push(`- fixture: \`${testItem?.audit ?? 'missing'}\``);
    lines.push(`- fingerprint: \`${testItem?.fingerprint ?? 'missing'}\``);
    lines.push(`- agent_included_test_finding: ${testItem?.agent_included ?? false}`);
    lines.push(`- decision: ${testItem?.decision ?? 'missing'}`);
    if (testItem?.duplicate) {
      lines.push(`- dedup: issue #${testItem.duplicate.number} (${testItem.duplicate.state})`);
    }
    lines.push(
      `- outcome: ${
        testItem?.decision === 'created'
          ? `created ${testItem.issueUrl}`
          : testItem?.decision === 'duplicate'
            ? `skipped duplicate of #${testItem.duplicate?.number}`
            : testItem?.decision === 'not_actionable'
              ? 'not published: the synthetic fixture failed validation'
              : plan.createIssues
                ? 'proposed; the create step re-checks and creates'
                : 'dry-run: proposed, not published'
      }`,
    );
    const real = plan.items.filter((item) => item.kind === 'real');
    lines.push(
      `- real findings in test_mode: ${real.length} analysed, 0 published (suppressed)`,
    );
  }
  lines.push('');
  lines.push('## Findings', '');
  if (plan.items.length === 0) {
    lines.push('No finding was analysed.');
    lines.push('');
  } else {
    lines.push('| Kind | Audit | Route | Fingerprint | Decision | Issue |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const item of plan.items) {
      const issue = item.duplicate ? `#${item.duplicate.number} (${item.duplicate.state})` : item.issueUrl ?? '';
      lines.push(
        `| ${item.kind} | ${item.audit ?? ''} | ${item.route ?? ''} | \`${item.fingerprint ?? ''}\` | ${item.decision} | ${issue} |`,
      );
    }
    lines.push('');
    for (const item of plan.items) {
      if (!item.reason) continue;
      lines.push(`- \`${item.fingerprint ?? item.kind}\`: ${item.reason}`);
    }
    lines.push('');
  }
  if (!plan.createIssues) {
    lines.push(
      'Dry run: `create_issues=false`, so no issue was published. Proposed payloads are in `proposed-issue.md`.',
    );
    lines.push('');
  }
  return lines.join('\n');
}

export function renderProposed(plan) {
  const lines = ['# Proposed issues', ''];
  lines.push(
    plan.createIssues
      ? 'Nothing was created yet: the create step re-checks deduplication before each `gh issue create`.'
      : 'Dry run: `create_issues=false`, so nothing is published. These payloads would have been submitted.',
  );
  lines.push('');
  const proposed = plan.items.filter(
    (item) => item.decision === 'create' || item.decision === 'duplicate',
  );
  if (proposed.length === 0) {
    lines.push('No issue would be created in this run.');
    lines.push('');
  }
  for (const item of proposed) {
    lines.push(`## ${item.title}`);
    lines.push('');
    lines.push(
      `- Would: ${
        item.decision === 'create'
          ? 'create a new issue'
          : `skip: duplicate of #${item.duplicate.number}`
      }`,
    );
    lines.push(`- Labels: ${item.labels.map((label) => `\`${label}\``).join(', ')}`);
    lines.push(`- Fingerprint: \`${item.fingerprint}\``);
    lines.push('');
    lines.push('<details><summary>Issue body</summary>');
    lines.push('');
    lines.push(item.body);
    lines.push('');
    lines.push('</details>');
    lines.push('');
  }
  return lines.join('\n');
}

export function summaryLines(plan, { testMode, createIssues, runUrl }) {
  const testItem = plan.items.find((item) => item.kind === 'test');
  const created = plan.items.filter((item) => item.decision === 'created');
  const lines = [
    '## Lighthouse audit',
    '',
    `- Event: \`${plan.eventName ?? 'unknown'}\``,
    `- test_mode: ${testMode}`,
    `- create_issues: ${createIssues}`,
    `- Real findings: ${plan.counts.real} (published ${created.filter((item) => item.kind === 'real').length})`,
  ];
  if (testMode && testItem) {
    lines.push(`- Test finding: \`${testItem.fingerprint}\` — ${testItem.decision}`);
    if (testItem.duplicate) {
      lines.push(`  - deduplicated against #${testItem.duplicate.number} (${testItem.duplicate.state})`);
    }
    if (testItem.issueUrl) lines.push(`  - created ${testItem.issueUrl}`);
  }
  for (const item of created) {
    lines.push(`- Created #${issueNumber(item.issueUrl)} ${item.kind === 'test' ? '(test)' : ''}`.trim());
  }
  if (created.length === 0) lines.push('- No issue was created');
  if (runUrl) lines.push(`- [Workflow run](${runUrl})`);
  lines.push('');
  return lines.join('\n');
}

function parseArgs(argv) {
  const args = {
    report: 'report.md',
    out: 'decisions.md',
    issues: 'issues.md',
    proposed: 'proposed-issue.md',
    appUrl: process.env.APP_URL ?? '',
    runUrl: process.env.RUN_URL ?? '',
  };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    switch (value) {
      case '--report':
        args.report = argv[++index];
        break;
      case '--out':
        args.out = argv[++index];
        break;
      case '--issues':
        args.issues = argv[++index];
        break;
      case '--proposed':
        args.proposed = argv[++index];
        break;
      case '--audits':
        args.audits = argv[++index];
        break;
      case '--app-url':
        args.appUrl = argv[++index];
        break;
      case '--run-url':
        args.runUrl = argv[++index];
        break;
      default:
        throw new Error(`unknown argument: ${value}`);
    }
  }
  return args;
}

function fail(message) {
  console.error(`::error::${message}`);
  process.exit(1);
}

const PREVIEW_USAGE =
  'usage: node scripts/lighthouse-issues.mjs preview --report <report.md> --audits <audits.json> [--out <decisions.md>] [--issues <issues.md>] [--proposed <proposed-issue.md>] [--app-url <url>] [--run-url <url>]';

function main() {
  const argv = process.argv.slice(2);
  const command = argv[0];
  if (command !== 'preview' && command !== 'create') {
    fail('usage: node scripts/lighthouse-issues.mjs <preview|create> [options]');
  }
  const preview = command === 'preview';
  let args;
  try {
    args = parseArgs(argv.slice(1));
  } catch (error) {
    fail(error.message);
  }
  if (preview && !args.audits) {
    fail(
      `preview requires --audits so findings are validated against the audit scope. ${PREVIEW_USAGE}`,
    );
  }

  const eventName = process.env.GITHUB_EVENT_NAME ?? (preview ? 'local-preview' : '');
  const repo = process.env.GITHUB_REPOSITORY;
  if (!eventName) fail('GITHUB_EVENT_NAME is required');
  if (!preview && !repo) fail('GITHUB_REPOSITORY is required');

  let testMode;
  let createIssues;
  try {
    testMode =
      preview && process.env.TEST_MODE === undefined
        ? false
        : parseBooleanEnv(process.env.TEST_MODE, 'TEST_MODE');
    // A local preview is always a dry run, even if the workflow environment
    // happens to contain CREATE_ISSUES=true.
    createIssues = preview
      ? false
      : parseBooleanEnv(process.env.CREATE_ISSUES, 'CREATE_ISSUES');
    if (!preview) assertTestModeAllowed({ testMode, eventName });
  } catch (error) {
    fail(error.message);
  }
  if (command === 'create' && !createIssues) {
    fail('the create command must not run when create_issues=false');
  }

  let report;
  try {
    report = readFileSync(args.report, 'utf8');
  } catch (error) {
    fail(`cannot read the analysis report ${args.report}: ${error.message}`);
  }
  let scope = null;
  if (args.audits) {
    try {
      scope = JSON.parse(readFileSync(args.audits, 'utf8'));
    } catch (error) {
      fail(`cannot read the audit scope ${args.audits}: ${error.message}`);
    }
  }
  const links = { runUrl: args.runUrl, appUrl: args.appUrl };
  // `gh issue list` needs a repository and network access. A local preview is
  // self-contained and uses an empty deduplication state instead.
  const existingReal = preview
    ? []
    : collectIssues({ runGh: defaultRunGh, repo, label: LIGHTHOUSE_LABEL });
  const existingTest =
    !preview && testMode
      ? collectIssues({ runGh: defaultRunGh, repo, label: LIGHTHOUSE_TEST_LABEL })
      : [];

  const plan = planIssues({
    report,
    testMode,
    createIssues,
    existingReal,
    existingTest,
    links,
    scope,
  });
  plan.eventName = eventName;

  const executed =
    command === 'create'
      ? executePlan({ plan, runGh: defaultRunGh, repo, links, testMode })
      : plan;

  const decisions = renderDecisions(executed, {
    eventName,
    testMode,
    appUrl: args.appUrl,
  });
  writeFileSync(args.out, decisions);
  writeFileSync(args.issues, renderIssues(executed));
  writeFileSync(args.proposed, renderProposed(executed));

  const summary = summaryLines(executed, { testMode, createIssues, runUrl: args.runUrl });
  if (process.env.GITHUB_STEP_SUMMARY) {
    appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary);
  }

  if (testMode && process.env.GITHUB_STEP_SUMMARY) {
    appendFileSync(
      process.env.GITHUB_STEP_SUMMARY,
      '> test_mode is enabled: the created issue is synthetic and labelled `lighthouse-test`.\n',
    );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(`::error::${error.message}`);
    process.exit(1);
  }
}
